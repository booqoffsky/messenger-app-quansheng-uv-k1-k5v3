/* ---- sampling (APRS RX): the PA4 capture and the 48 MHz cycle clock are
 * resident (API level 3); the capture holds PA4 at mid-scale (code 2048) ---- */
#define FS             9600u
#define CYC_PER_SAMPLE (48000000u / FS)     /* 5000 */
#define HOUSE_EVERY    480u    /* samples between key/screen slots (50 ms)     */
#define BUSY_MAX       60u     /* serve them anyway after 60 busy slots (3 s)  */

/* ---- demodulator (APRS RX, test/model_rx.py, class Demod) ---- */
#define BP_B0       5356   /* band-pass 1625 Hz, Q 0.9, Q14 (b2 = -b0, b1 = 0) */
#define BP_A1     (-10714)
#define BP_A2       5673
#define AGC_ATT     5      /* peak tracker attack, 1/32                       */
#define AGC_DEC     10     /* peak tracker decay, 1/1024 per sample           */
#define PK_MIN      16
#define PLL_STEP    8192   /* 65536 per bit / 8 samples per bit               */
#define PLL_CTR     36864  /* transitions pulled to mid-bit + half a sample   */
#define PLL_SHIFT   2      /* 1/4 of the error per transition                 */
#define NSL         3      /* slicers                                         */
#define PRE_BITS    24u    /* busy for 3 bytes past any flag                  */

/* ---- AX.25 ---- */
/* UI frame, no digipeaters, SSID 0: destination 0-6, source 7-13, control
 * 14, PID 15, payload 16, FCS little-endian at the end. */
#define SRC_OFF     7u      /* source address                                */
#define CTRL_OFF    14u
#define PID_OFF     15u
#define INFO_OFF    16u     /* payload start                                 */
#define SSID_DST    0x60u   /* SSID 0, no end bit                            */
#define SSID_SRC    0x61u   /* SSID 0 + address-field end bit                */
#define CTRL_UI     0x03u   /* unnumbered information                        */
#define PID_NONE    0xF0u   /* no layer-3 protocol                           */
#define FLAG        0x7Eu   /* HDLC flag                                     */
#define FCS_POLY    0x8408u /* CRC-16/X.25, reflected                        */
#define FRAME_MIN   24u     /* 2 addresses + control + PID + 6-byte payload + FCS */
#define FRAME_MAX   64u     /* 2 addresses + control + PID + 6 + 36 + FCS + slack  */
#define FCS_GOOD    0xF0B8u

/* ---- AFSK TX (APRS TX) ---- */
#define CYC_PER_BIT (48000000u / 1200u)     /* 40000: exact */
#define REG_51      0x51   /* sub-audio: 0 = no CTCSS/DCS                    */
#define REG_70      0x70   /* tone 1: <15> enable, <14:8> gain               */
#define REG_71      0x71   /* tone 1 frequency, Hz x 10.32444               */
#define F_MARK      12389u /* 1200 Hz */
#define F_SPACE     22714u /* 2200 Hz */
#define TX_LVL      66     /* BK4819_TransmitTone's tone gain (FT3D-proven)  */
#define TXDELAY_FLAGS 16u  /* 107 ms of flags before the frame               */
#define TAIL_FLAGS  2u

/* Messenger payload (after the AX.25 UI header): "AM", version 1, then... */
enum { Q_VER = 2, Q_TYPE = 3, Q_ID = 4, Q_TEXT = 6 };
enum { PKT_TEXT = 1, PKT_ACK = 2 };

enum { SCREEN_LIST = 0, SCREEN_READ, SCREEN_COMPOSE };
enum { ST_NONE = 0, ST_SENT, ST_ACK, ST_NOACK, ST_DENIED };
enum { AL_NONE = 0, AL_TEXT, AL_ACK };           /* inbound alert codes     */
enum { MODE_UPPER = 0, MODE_NUM };               /* multi-tap input modes */

#define UI_SIZE KEYMAP      /* the UI assets end where the keymap begins */

